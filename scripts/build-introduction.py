#!/usr/bin/env python3
"""Generate the static reading page from the introduction's Markdown source."""

from pathlib import Path
import re
import sys

try:
    import markdown
    from markdown.extensions.toc import TocExtension, slugify_unicode
except ImportError:
    sys.exit("Install documentation dependencies: python -m pip install -r requirements-docs.txt")


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/00-introduction.md"
TARGET = ROOT / "site/index.html"


def build():
    converter = markdown.Markdown(
        extensions=[
            "tables",
            "fenced_code",
            TocExtension(slugify=slugify_unicode, toc_depth="2-2"),
        ]
    )
    article = converter.convert(SOURCE.read_text(encoding="utf-8"))
    article = article.replace('src="../site/images/', 'src="images/')
    article = article.replace("<table>", '<div class="table-wrapper"><table>')
    article = article.replace("</table>", "</table></div>")
    article = re.sub(
        r'<p>(<img [^>]+>)</p>',
        r'<div class="diagram-scroll">\1</div>',
        article,
    )

    page = """<!DOCTYPE html>
<html lang="zh-CN">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="description" content="从开门亮灯追踪智能家居系统的设备、通信网络、协议接入、控制平台与云端依赖。">
  <title>智能家居系统原理设计 | 系统组成与通信</title>
  <link rel="stylesheet" href="css/style.css">
  <link rel="stylesheet" href="css/introduction.css">
</head>
<body>
  <!-- Generated by scripts/build-introduction.py; edit docs/00-introduction.md. -->
  <a class="skip-link" href="#introduction">跳到正文</a>
  <div class="overlay" aria-hidden="true"></div>
  <aside class="sidebar" id="reading-menu">
    <div class="sidebar-header">
      <p class="book-name">智能家居系统原理设计</p>
      <p class="subtitle">开篇 · 系统组成与通信</p>
    </div>
    <nav class="sidebar-nav" aria-label="开篇目录">
__TOC__
    </nav>
    <div class="reading-links">
      <a href="https://github.com/JacoCheung/home-lab">GitHub 仓库</a>
      <a href="https://github.com/JacoCheung/home-lab/tree/archived_main">原方案归档 · archived_main</a>
    </div>
  </aside>
  <main class="main">
    <header class="header">
      <button class="hamburger" aria-label="打开阅读目录" aria-controls="reading-menu" aria-expanded="false">☰</button>
      <p class="page-title">智能家居系统原理设计</p>
    </header>
    <div class="content reading-content">
      <article class="prose" id="introduction">
__ARTICLE__
      </article>
    </div>
  </main>
  <script>
    const menuButton = document.querySelector('.hamburger');
    const menu = document.querySelector('.sidebar');
    const overlay = document.querySelector('.overlay');
    function setMenu(open) {
      menu.classList.toggle('open', open);
      overlay.classList.toggle('open', open);
      menuButton.setAttribute('aria-expanded', String(open));
      menuButton.setAttribute('aria-label', open ? '关闭阅读目录' : '打开阅读目录');
    }
    menuButton.addEventListener('click', () => setMenu(!menu.classList.contains('open')));
    overlay.addEventListener('click', () => setMenu(false));
    menu.querySelectorAll('a').forEach(link => link.addEventListener('click', () => setMenu(false)));
    document.addEventListener('keydown', event => {
      if (event.key === 'Escape' && menu.classList.contains('open')) {
        setMenu(false);
        menuButton.focus();
      }
    });
  </script>
</body>
</html>
"""
    TARGET.write_text(
        page.replace("__TOC__", converter.toc).replace("__ARTICLE__", article),
        encoding="utf-8",
    )
    print(f"Generated {TARGET.relative_to(ROOT)} from {SOURCE.relative_to(ROOT)}")


if __name__ == "__main__":
    build()
